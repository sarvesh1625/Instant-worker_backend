const crypto = require('crypto');
const axios  = require('axios');
const Otp    = require('../models/Otp');

const CODE_TTL_MS   = 10 * 60 * 1000; // code valid 10 min
const COOLDOWN_MS   = 30 * 1000;      // min gap between sends to same number
const WINDOW_MS     = 60 * 60 * 1000; // send-count window
const MAX_SENDS     = 5;              // per number, per purpose, per window
const MAX_ATTEMPTS  = 5;              // wrong guesses per code

const normalizePhone = (p) => {
  if (typeof p !== 'string') return null;       // blocks {"$ne":""} style payloads
  const s = p.trim();
  return /^\d{10}$/.test(s) ? s : null;
};

const keyOf = (purpose, phone) => `${purpose}:${phone}`;
const hash  = (key, code) =>
  crypto.createHmac('sha256', process.env.JWT_SECRET).update(`${key}:${code}`).digest('hex');

// 'dev'  -> no SMS, code printed in SERVER console only (never in the API response)
// anything else (incl. unset) -> real SMS via MSG91, and fails closed if not configured
const isDevMode  = () => process.env.OTP_MODE === 'dev';
// 'test' -> TEMPORARY, for closed testing only: no SMS, code is RETURNED in the API response
// (app shows it in the yellow box). Anyone can reset any account's password in this mode.
const isTestMode = () => process.env.OTP_MODE === 'test';

// Widget mode: MSG91 itself generates + sends + checks the OTP (default template, no DLT template id).
// Used for BOTH website and mobile register / forgot-password, so no OTP is generated by us.
// Turned on by MSG91_WIDGET_ID + MSG91_TOKEN_AUTH (both public widget values) and overrides OTP_MODE=test.
const widgetId  = () => String(process.env.MSG91_WIDGET_ID || '').trim();
const tokenAuth = () => String(process.env.MSG91_TOKEN_AUTH || '').trim();
const widgetOn  = () => !!(widgetId() && tokenAuth()) && !isDevMode();
const otpLength = () => (widgetOn() ? (parseInt(process.env.MSG91_OTP_LENGTH, 10) || 4) : 6);

// OTP_DEBUG=on (temporary!) puts MSG91's own reason into the error text, so a failed send can be diagnosed without logs.
const debugOn = () => String(process.env.OTP_DEBUG || '').toLowerCase() === 'on';

// MSG91's own docs use api.msg91.com; the dashboard host control.msg91.com is what we tested from a PC.
// If one host answers with an IP/"Invalid request"-type refusal, the other is tried once.
const HOSTS = ['control.msg91.com', 'api.msg91.com'];
const hostRefusal = (d) => d?.type === 'error' && /invalid request|ipblocked|authenticationfailure|^HTTP /i.test(String(d.message || ''));

async function widgetCallOn(host, path, body) {
  const r = await axios.post(`https://${host}/api/v5/widget/${path}`,
    { widgetId: widgetId(), tokenAuth: tokenAuth(), ...body },
    { headers: { 'Content-Type': 'application/json', Accept: 'application/json' }, timeout: 15000, validateStatus: () => true });
  // If MSG91 (or something in front of it) answers with a web page instead of JSON, keep a short piece of it.
  return (r.data && typeof r.data === 'object') ? r.data : { type: 'error', message: `HTTP ${r.status} ${String(r.data || '').slice(0, 100)}` };
}

async function widgetCall(path, body) {
  try {
    let first = null;
    for (const host of HOSTS) {
      let d;
      try { d = await widgetCallOn(host, path, body); }
      catch (err) { if (host === HOSTS[HOSTS.length - 1] && !first) throw err; continue; }
      if (!hostRefusal(d)) return d;          // success, or a normal answer such as "wrong OTP"
      console.error(`MSG91 widget ${path} refused on ${host}:`, JSON.stringify(d));
      if (!first) first = d;
    }
    return first;
  } catch (err) {
    console.error('MSG91 widget network error:', path, err.message);
    const e = new Error(debugOn() ? `Could not reach MSG91: ${err.message}` : 'Could not reach the SMS service. Please try again.'); e.status = 502; throw e;
  }
}

async function widgetSend(phone) {
  const d = await widgetCall('sendOtpMobile', { identifier: `91${phone}` });
  if (d.type !== 'success' || typeof d.message !== 'string' || !d.message) {
    console.error('MSG91 widget send rejected:', JSON.stringify(d));
    const why = String(d.message || d.type || 'no reply').slice(0, 150);
    const e = new Error(debugOn() ? `MSG91 refused to send: ${why}` : 'Could not send SMS. Please try again.'); e.status = 502; throw e;
  }
  return d.message; // reqId
}

// verifyOtp's reply has the JWT in `message` and no `type` field on success (checked live).
async function widgetVerify(reqId, otp) {
  const d = await widgetCall('verifyOtp', { reqId, otp });
  const ok = d.type !== 'error' && typeof d.message === 'string' && d.message.startsWith('eyJ');
  if (!ok) console.log('MSG91 widget verify said:', JSON.stringify({ type: d.type, message: typeof d.message === 'string' ? d.message.slice(0, 80) : d.message }));
  return ok;
}

async function sendSms(phone, code) {
  const { MSG91_AUTHKEY, MSG91_TEMPLATE_ID } = process.env;
  if (!MSG91_AUTHKEY) {
    const e = new Error('SMS service is not configured'); e.status = 500; throw e;
  }
  try {
    const r = await axios.post(
      'https://control.msg91.com/api/v5/otp',
      { OTP: code },                       // template variable ##OTP##
      {
        params: {
          ...(MSG91_TEMPLATE_ID && { template_id: MSG91_TEMPLATE_ID }), // optional: MSG91 default template if unset
          mobile: `91${phone}`,
          otp: code,                       // our own code, so we can verify it ourselves
          otp_expiry: Math.round(CODE_TTL_MS / 60000),
        },
        headers: { authkey: MSG91_AUTHKEY, 'Content-Type': 'application/json' },
        timeout: 10000,
      }
    );
    if (r.data?.type !== 'success') {
      console.error('MSG91 send rejected:', JSON.stringify(r.data));
      const e = new Error('Could not send SMS. Please try again.'); e.status = 502; throw e;
    }
  } catch (err) {
    if (err.status) throw err;
    console.error('MSG91 send error:', err.response?.data || err.message);
    const e = new Error('Could not send SMS. Please try again.'); e.status = 502; throw e;
  }
}

/**
 * Create + send an OTP.
 * Returns { sent: true } or { sent: false, reason: 'cooldown'|'limit' }.
 * Throws {status,message} if SMS delivery fails.
 */
async function sendOtp(phone, purpose) {
  const key = keyOf(purpose, phone);
  const now = Date.now();
  const doc = await Otp.findOne({ phone: key });

  if (doc) {
    if (doc.lastSentAt && now - doc.lastSentAt.getTime() < COOLDOWN_MS) return { sent: false, reason: 'cooldown' };
    if (doc.sendCount >= MAX_SENDS) return { sent: false, reason: 'limit' };
  }

  const widget = widgetOn();
  const code = widget ? 'widget' : crypto.randomInt(100000, 1000000).toString();
  const prev = doc ? { lastSentAt: doc.lastSentAt, sendCount: doc.sendCount } : null;

  // Widget mode: MSG91 sends first; only a successful send touches our cooldown/quota.
  let reqId;
  if (widget) reqId = await widgetSend(phone);

  await Otp.findOneAndUpdate(
    { phone: key },
    {
      $set: {
        code: hash(key, code), attempts: 0, ...(widget ? { reqId } : { reqId: null }),
        codeExpiresAt: new Date(now + CODE_TTL_MS), lastSentAt: new Date(now),
        ...(doc ? {} : { expiresAt: new Date(now + WINDOW_MS) }),
      },
      $inc: { sendCount: 1 },
    },
    { upsert: true, new: true, setDefaultsOnInsert: true }
  );

  try {
    if (widget) { /* already sent by MSG91 */ }
    else if (isTestMode()) console.warn(`[OTP TEST MODE - INSECURE] ${purpose} ${phone}: ${code}`);
    else if (isDevMode()) console.log(`[OTP dev] ${purpose} ${phone}: ${code}`);
    else await sendSms(phone, code);
  } catch (err) {
    // SMS failed -> don't burn the user's cooldown / quota
    if (prev) await Otp.updateOne({ phone: key }, { $set: { lastSentAt: prev.lastSentAt, sendCount: prev.sendCount } });
    else await Otp.deleteOne({ phone: key });
    throw err;
  }
  return isTestMode() && !widget ? { sent: true, devCode: code } : { sent: true };
}

/** Check a code. Consumes it on success. Returns { ok:true } or { ok:false, message }. */
async function verifyOtp(phone, purpose, code) {
  const key = keyOf(purpose, phone);
  const c = typeof code === 'string' ? code.trim() : '';
  const len = otpLength();
  if (!new RegExp(`^\\d{${len}}$`).test(c)) return { ok: false, message: `Enter the ${len}-digit OTP` };

  const doc = await Otp.findOne({ phone: key });
  if (!doc || !doc.codeExpiresAt) return { ok: false, message: 'No OTP found. Please request a new one.' };
  if (doc.codeExpiresAt.getTime() < Date.now()) return { ok: false, message: 'OTP expired. Please request a new one.' };
  if (doc.attempts >= MAX_ATTEMPTS) return { ok: false, message: 'Too many wrong attempts. Please request a new OTP.' };

  let match;
  if (widgetOn() && doc.reqId) {
    match = await widgetVerify(doc.reqId, c);   // MSG91 checks the code for the request WE created for this phone
  } else {
    const a = Buffer.from(hash(key, c)), b = Buffer.from(doc.code);
    match = a.length === b.length && crypto.timingSafeEqual(a, b);
  }
  if (!match) {
    // atomic increment so parallel guesses can't dodge the limit
    const upd = await Otp.findOneAndUpdate({ phone: key }, { $inc: { attempts: 1 } }, { new: true });
    const left = Math.max(0, MAX_ATTEMPTS - (upd?.attempts ?? MAX_ATTEMPTS));
    return { ok: false, message: left ? `Wrong OTP. ${left} attempt${left !== 1 ? 's' : ''} remaining.` : 'Too many wrong attempts. Please request a new OTP.' };
  }

  // consume atomically: only one request can win
  const del = await Otp.deleteOne({ _id: doc._id, code: doc.code });
  if (del.deletedCount !== 1) return { ok: false, message: 'OTP already used. Please request a new one.' };
  return { ok: true };
}

module.exports = { sendOtp, verifyOtp, normalizePhone, otpLength, widgetOn };